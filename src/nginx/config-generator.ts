import type { CompiledPolicy } from '../types.ts';
import { ConfigError } from '../errors.ts';

type RouteRule = { source: string; eligible: boolean };

const ROUTER_HEADERS = [
  '$http_rsc',
  '$http_next_action',
  '$http_next_router_state_tree',
  '$http_next_router_prefetch',
  '$http_next_router_segment_prefetch',
  '$http_next_url',
  '$http_x_nextjs_data',
];

export function generateNginxConfig(
  policy: CompiledPolicy,
  options?: { upstream?: string; releaseId?: string },
): string {
  if (options?.releaseId && options.releaseId !== policy.config.storage.releaseId) {
    throw new ConfigError('snippet releaseId must match storage.releaseId');
  }
  const endpoint = originEndpoint(policy, options?.upstream);
  return `# generated by @xoisr/html-cache
# release ${policy.config.storage.releaseId}
# Include this file once inside the site HTTPS server:
#     include /path/to/this-file.conf;
# It replaces the old location / proxy. Do not add a map or upstream in nginx.conf.
# Include it only on the HTTPS server. The site's own port 80 redirect runs first.
# The site access_log stays on. These variables are available to that log format:
# $html_cache_status cookie=$html_cache_cookie_bypass query_ok=$html_cache_query_ok
# purgeAll keeps this root path: it moves the live directory aside and creates an empty one.
${renderServer(policy, endpoint)}
`;
}

export function nginxRouteAllowed(policy: CompiledPolicy, rawPath: string): boolean {
  for (const rule of routeRules(policy)) {
    if (new RegExp(rule.source).test(rawPath)) return rule.eligible;
  }
  return false;
}

function renderServer(policy: CompiledPolicy, endpoint: string): string {
  const { config } = policy;
  const root = nginxPath(`${config.storage.directory}/${config.storage.releaseId}`);
  const maintenance = nginxPath(`${config.storage.directory}/control/maintenance`);
  const pub = new URL(config.origin.publicUrl);
  const base = config.origin.basePath;
  const prefixes = new Set<string>([
    '/.well-known/',
    `${base}/_next/static/`,
    `${base}/_next/image`,
    `${base}/_next/data/`,
    `${base}/api/`,
  ]);
  for (const pattern of config.policy.exclude) {
    if (pattern === `${base}/_next/**`) continue;
    const prefix = prefixOf(pattern);
    if (prefix) prefixes.add(prefix);
  }
  const staticPrefix = `${base}/_next/static/`;
  const blocks = [
    `# hiden-block:vars
set $html_cache_status "";
set $html_cache_cookie_bypass "";
set $html_cache_query_ok "";
# hiden-block:vars-end`,
    ...[...prefixes].map((prefix) =>
      prefix === staticPrefix ? staticLocation(policy, prefix, endpoint, pub) : proxyLocation(prefix, endpoint, pub),
    ),
    documentLocation(policy, maintenance, endpoint, pub),
    storeLocation(policy, root),
    missLocation(policy, endpoint, pub),
    routerLocation(policy, endpoint, pub),
  ];
  return blocks.join('\n\n');
}

function documentLocation(policy: CompiledPolicy, maintenance: string, endpoint: string, pub: URL): string {
  const https = pub.protocol === 'https:' ? `https://${pub.host}` : `${pub.protocol}//${pub.host}`;
  return `# hiden-block:document
location / {
    ${decisionDirectives(policy, maintenance)}
    set $html_cache_status BYPASS;
    error_page 419 = @hiden_router;
    if ($html_cache_router = "1") {
        return 419;
    }
    if ($html_cache_rsc_accept = "1") {
        return 419;
    }
    if ($html_cache_slash_path != "") {
        return 301 ${https}$html_cache_slash_path$is_args$args;
    }
    error_page 418 = @hiden_store;
    if ($html_cache_go = "1:0:1:1:1:1:0:0:0:0") {
        return 418;
    }
    ${proxyDirectives(endpoint, pub)}
    proxy_hide_header Cache-Control;
    ${documentHeaders(policy, '$html_cache_status')}
}
# hiden-block:document-end`;
}

function decisionDirectives(policy: CompiledPolicy, maintenance: string): string {
  const rawPath = [
    'set $hiden_raw_path $request_uri;',
    'if ($request_uri ~ "^(?<hiden_raw>[^?]*)") { set $hiden_raw_path $hiden_raw; }',
    'set $html_cache_path_ok 0;',
    'if ($hiden_raw_path = "/") { set $html_cache_path_ok 1; }',
    'if ($hiden_raw_path ~ "^/(?:[A-Za-z0-9._~-]{1,255})(?:/[A-Za-z0-9._~-]{1,255})*$") { set $html_cache_path_ok 1; }',
    'if ($hiden_raw_path ~ "(?:^|/)[.]{1,2}(?:/|$)") { set $html_cache_path_ok 0; }',
    'set $html_cache_slash_path "";',
    'if ($hiden_raw_path ~ "^(?<slash_path>.+)/$") { set $html_cache_slash_path $slash_path; }',
    'if ($hiden_raw_path ~ "%") { set $html_cache_slash_path ""; }',
    'if ($hiden_raw_path ~ "//") { set $html_cache_slash_path ""; }',
  ];
  const query = [
    'set $html_cache_query_ok 0;',
    'set $html_cache_query_dir "";',
    'if ($args = "") {',
    '    set $html_cache_query_ok 1;',
    '}',
    ...policy.queryRules.flatMap((rule) => [
      `if ($args ~ "${rule.source}") {`,
      '    set $html_cache_query_ok 1;',
      `    set $html_cache_query_dir "${rule.directory}";`,
      '}',
    ]),
  ];
  const includes = routeRules(policy).filter((rule) => rule.eligible);
  const excludes = routeRules(policy).filter((rule) => !rule.eligible);
  const routes = ['set $html_cache_route 0;', ...[...includes, ...excludes].map((rule) => routeIf(rule))];
  const flags = [
    'set $html_cache_method_ok 0;',
    'if ($request_method = GET) { set $html_cache_method_ok 1; }',
    'if ($request_method = HEAD) { set $html_cache_method_ok 1; }',
    'set $html_cache_cookie_bypass 1;',
    'if ($http_cookie = "") { set $html_cache_cookie_bypass 0; }',
    'set $html_cache_auth 1;',
    'if ($http_authorization = "") { set $html_cache_auth 0; }',
    'set $html_cache_dest_ok 0;',
    'if ($http_sec_fetch_dest = "") { set $html_cache_dest_ok 1; }',
    'if ($http_sec_fetch_dest = document) { set $html_cache_dest_ok 1; }',
    'set $html_cache_router 0;',
    ...ROUTER_HEADERS.map((header) => `if (${header} != "") { set $html_cache_router 1; }`),
    'if ($args ~ "(?:^|&)_rsc=") { set $html_cache_router 1; }',
    'set $html_cache_rsc_accept 0;',
    'if ($http_accept ~* "text/x-component") { set $html_cache_rsc_accept 1; }',
    'set $html_cache_maintenance 0;',
    `if (-f "${maintenance}") { set $html_cache_maintenance 1; }`,
    'set $hiden_file "/index.html";',
    'if ($hiden_raw_path != "/") { set $hiden_file "$hiden_raw_path/index.html"; }',
    'set $hiden_query_at "/@";',
    'if ($hiden_raw_path != "/") { set $hiden_query_at "$hiden_raw_path/@"; }',
    'if ($html_cache_query_dir != "") { set $hiden_file "$hiden_query_at$html_cache_query_dir/index.html"; }',
    'set $html_cache_go "$html_cache_method_ok:$html_cache_cookie_bypass:$html_cache_route:$html_cache_path_ok:$html_cache_query_ok:$html_cache_dest_ok:$html_cache_router:$html_cache_rsc_accept:$html_cache_auth:$html_cache_maintenance";',
  ];
  return [...rawPath, ...query, ...routes, ...flags].join('\n    ');
}

function routeIf(rule: RouteRule): string {
  return `if ($hiden_raw_path ~ "${rule.source}") { set $html_cache_route ${rule.eligible ? 1 : 0}; }`;
}

function storeLocation(policy: CompiledPolicy, root: string): string {
  const gzip =
    policy.config.document.compression === 'nginx'
      ? `gzip_static on;
    gzip on;
    gzip_vary on;
    gzip_proxied off;`
      : '# compression off';
  return `# hiden-block:store
location @hiden_store {
    internal;
    root "${root}";
    open_file_cache off;
    expires off;
    set $html_cache_status HIT;
    try_files $hiden_file @hiden_miss;
    ${gzip}
    ${documentHeaders(policy, 'HIT')}
}
# hiden-block:store-end`;
}

function missLocation(policy: CompiledPolicy, endpoint: string, pub: URL): string {
  return `# hiden-block:miss
location @hiden_miss {
    internal;
    set $html_cache_status MISS;
    ${proxyDirectives(endpoint, pub)}
    proxy_hide_header Cache-Control;
    ${documentHeaders(policy, 'MISS')}
}
# hiden-block:miss-end`;
}

function staticLocation(policy: CompiledPolicy, prefix: string, endpoint: string, pub: URL): string {
  const current = policy.config.origin.staticRoot;
  if (!current) return proxyLocation(prefix, endpoint, pub);
  const previous = policy.config.origin.previousStaticRoot;
  const missing = previous ? '@hiden_static_prev' : '@hiden_static_proxy';
  const blocks = [
    `# hiden-block:_nextstatic
location ^~ ${prefix} {
    alias "${nginxPath(current)}/_next/static/";
    error_page 404 = ${missing};
    add_header Cache-Control "public, max-age=31536000, immutable" always;
}
# hiden-block:_nextstatic-end`,
  ];
  if (previous) {
    blocks.push(`# hiden-block:static-prev
location @hiden_static_prev {
    internal;
    ${staticRewrite(policy.config.origin.basePath)}
    root "${nginxPath(previous)}";
    try_files $uri @hiden_static_proxy;
    add_header Cache-Control "public, max-age=31536000, immutable" always;
}
# hiden-block:static-prev-end`);
  }
  blocks.push(staticProxyLocation(policy, endpoint, pub));
  return blocks.join('\n\n');
}

function staticRewrite(basePath: string): string {
  const source = basePath === '' ? '^(/_next/static/.*)$' : `^${escapeRegex(basePath)}(/_next/static/.*)$`;
  return `rewrite ${source} $1 break;`;
}

function staticProxyLocation(policy: CompiledPolicy, endpoint: string, pub: URL): string {
  const base = policy.config.origin.basePath;
  const restore = base === '' ? '' : `rewrite ^/_next/static/(.*)$ ${base}/_next/static/$1 break;\n    `;
  return `# hiden-block:static-proxy
location @hiden_static_proxy {
    internal;
    ${restore}${proxyDirectives(endpoint, pub)}
    # keep the origin cache header when the static file is missing
}
# hiden-block:static-proxy-end`;
}

function proxyLocation(prefix: string, endpoint: string, pub: URL): string {
  const label = prefix.replaceAll('/', '') || 'root';
  return `# hiden-block:${label}
location ^~ ${prefix} {
    ${proxyDirectives(endpoint, pub)}
    # keep the origin cache header on this prefix
}
# hiden-block:${label}-end`;
}

function proxyDirectives(endpoint: string, pub: URL): string {
  const proto = pub.protocol.replace(':', '');
  return `proxy_pass ${endpoint};
    proxy_set_header Host ${pub.host};
    proxy_set_header X-Forwarded-Host ${pub.host};
    proxy_set_header X-Forwarded-Proto ${proto};
    proxy_set_header Accept-Encoding $http_accept_encoding;
    proxy_http_version 1.1;
    proxy_set_header Connection "";`;
}

function routerLocation(policy: CompiledPolicy, endpoint: string, pub: URL): string {
  const debug = policy.config.debug ? '\n    add_header X-HTML-Cache-Debug $html_cache_go always;' : '';
  return `# hiden-block:router
location @hiden_router {
    internal;
    set $html_cache_status BYPASS;
    ${proxyDirectives(endpoint, pub)}
    add_header X-HTML-Cache BYPASS always;${debug}
}
# hiden-block:router-end`;
}

function documentHeaders(policy: CompiledPolicy, status: string): string {
  const lines = [
    `add_header Cache-Control ${nginxQuote(policy.config.document.cacheControl)} always;`,
    `add_header X-HTML-Cache ${status} always;`,
  ];
  for (const [name, value] of Object.entries(policy.config.document.securityHeaders)) {
    lines.push(`add_header ${name} ${nginxQuote(value)} always;`);
  }
  if (policy.config.debug) {
    lines.push('add_header X-HTML-Cache-Debug $html_cache_go always;');
  }
  return lines.join('\n    ');
}

function routeRules(policy: CompiledPolicy): RouteRule[] {
  const excludes = policy.config.policy.exclude.map((pattern) => ({ source: globSource(pattern), eligible: false }));
  const includes = policy.config.policy.include.map((pattern) => ({ source: globSource(pattern), eligible: true }));
  return [...excludes, ...includes];
}

function globSource(pattern: string): string {
  const segments = pattern.split('/').filter((segment) => segment.length > 0);
  if (segments.length === 0) return '^/$';
  if (segments.at(-1) === '**') {
    const head = segments.slice(0, -1);
    if (head.length === 0) return '^/';
    const prefix = `/${head.map(escapeRegex).join('/')}`;
    return `^${prefix}(?:/.*)?$`;
  }
  if (segments.at(-1) === '*') {
    const prefix = `/${segments.slice(0, -1).map(escapeRegex).join('/')}`;
    return `^${prefix}/[^/]+$`;
  }
  return `^/${segments.map(escapeRegex).join('/')}$`;
}

function prefixOf(pattern: string): string | null {
  const segments = pattern.split('/').filter((segment) => segment.length > 0);
  if (segments.length === 0 || segments.at(-1) === '*') return null;
  if (segments.at(-1) === '**') return `/${segments.slice(0, -1).join('/')}/`;
  return `/${segments.join('/')}`;
}

function originEndpoint(policy: CompiledPolicy, upstream: string | undefined): string {
  const url = new URL(upstream ?? policy.config.origin.internalUrl);
  return `${url.protocol}//${url.host}`;
}

function nginxPath(value: string): string {
  return value.replaceAll('\\', '/');
}

function nginxQuote(value: string): string {
  return `"${value.replaceAll('\\', '\\\\').replaceAll('"', '\\"')}"`;
}

function escapeRegex(value: string): string {
  return value.replace(/[\\^$+?.()|[\]{}]/g, '\\$&');
}
